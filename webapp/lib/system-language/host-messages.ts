export function formatHostGlossaryLabel(value: string, translate: (key: string, values?: Record<string, string | number>) => string): string {
  const count = /^(\d+)개 (선택|적용)$/u.exec(value);
  if (count) return translate(count[2] === "선택" ? "{count}개 선택" : "{count}개 적용", { count: count[1] });
  const version = /^(.*) · 활성 버전 (\d+) · 총 (\d+)개$/u.exec(value);
  // Names are user content; only the known system suffix is localized.
  if (version) return `${version[1]} · ${translate("활성 버전 {version} · 총 {count}개", { version: version[2], count: version[3] })}`;
  return translate(value);
}
