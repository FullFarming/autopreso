type GlossaryText = (key: string, values?: SystemTextValues) => string;

export function formatGlossaryLanguageTag(tag: string, t: GlossaryText): string {
  const source = /^원문 ([a-zA-Z-]+)$/u.exec(tag);
  return source ? t("원문 {language}", { language: source[1] }) : tag;
}

export function formatGlossaryStatus(message: string, t: GlossaryText): string {
  const patterns: readonly (readonly [RegExp, string, string])[] = [
    [/^버전 (\d+)을 활성화했습니다\.$/u, "버전 {version}을 활성화했습니다.", "version"],
    [/^AI 후보 (\d+)개를 검토 목록에 추가했습니다\. 후보를 개별 승인해 주세요\.$/u, "AI 후보 {count}개를 검토 목록에 추가했습니다. 후보를 개별 승인해 주세요.", "count"],
    [/^(\d+)개 용어집을 선택했습니다\.$/u, "{count}개 용어집을 선택했습니다.", "count"],
    [/^같은 용어의 번역이 충돌합니다: ([\s\S]*)$/u, "같은 용어의 번역이 충돌합니다: {terms}", "terms"],
    [/^지원하지 않는 번역 언어입니다: ([\s\S]*)$/u, "지원하지 않는 번역 언어입니다: {language}", "language"],
  ];
  for (const [pattern, key, parameter] of patterns) {
    const match = pattern.exec(message);
    if (match) return t(key, { [parameter]: match[1] });
  }
  return t(message);
}

export function formatGlossaryVersionDescription(description: string, t: GlossaryText): string {
  const version = /^(.*) · 활성 버전 (\d+)$/u.exec(description);
  return version ? `${version[1]} · ${t("활성 버전 {version}", { version: version[2] })}` : description;
}
