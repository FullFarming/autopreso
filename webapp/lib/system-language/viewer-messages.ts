export function formatViewerSystemStatus(message: string, t: (key: string, values?: SystemTextValues) => string): string {
  const reconnect = /^Reconnecting · retrying in (\d+(?:\.\d+)?)s$/u.exec(message);
  return reconnect ? t("다시 연결 중 · {seconds}초 후 재시도", { seconds: reconnect[1] }) : t(message);
}
