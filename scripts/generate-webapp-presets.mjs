// Regenerates webapp/lib/presets.ts from the canonical desktop presets in
// src/glossary-presets.js so the two never drift. Run after editing presets:
//   node scripts/generate-webapp-presets.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { GLOSSARY_PRESETS } from "../src/glossary-presets.js";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const OUT = path.join(ROOT, "webapp", "lib", "presets.ts");

// Desktop preset id -> webapp preset id + webapp LanguagePairId.
const MAP = [
  // The everyday DEFAULT (general CRE consulting + business idioms) leads the
  // list: Live Call sessions are CRE work far more often than hotel or F&B ones.
  { from: "default-cre-ai-en-ko", id: "cre", pair: "ko-en" },
  { from: "hotel-investment-en-ko", id: "hospitality", pair: "ko-en" },
  { from: "fnb-leasing-ko-ja", id: "fnb", pair: "ko-ja" },
  { from: "hotel-investment-en-ja", id: "hotel-ja", pair: "en-ja" },
];

const entries = MAP.map(({ from, id, pair }) => {
  const preset = GLOSSARY_PRESETS.find((p) => p.id === from);
  if (!preset) throw new Error(`desktop preset not found: ${from}`);
  return `  {
    id: ${JSON.stringify(id)},
    label: ${JSON.stringify(preset.label)},
    languagePair: ${JSON.stringify(pair)},
    glossary: ${JSON.stringify(preset.glossary)},
    domain: ${JSON.stringify(preset.domain)},
  },`;
});

const hospitality = GLOSSARY_PRESETS.find((p) => p.id === "hotel-investment-en-ko");
const fnb = GLOSSARY_PRESETS.find((p) => p.id === "fnb-leasing-ko-ja");
const cre = GLOSSARY_PRESETS.find((p) => p.id === "default-cre-ai-en-ko");
if (!cre) throw new Error("desktop preset not found: default-cre-ai-en-ko");

const ts = `// AUTO-GENERATED by scripts/generate-webapp-presets.mjs — do not edit by hand.
// Source of truth: src/glossary-presets.js (and docs/glossary-*.txt behind it).

import type { LanguagePairId } from "./types";

export const GLOSSARY_GENERAL_CRE: string = ${JSON.stringify(cre.glossary)};

export const DOMAIN_GENERAL_CRE = ${JSON.stringify(cre.domain)};

export const GLOSSARY_HOSPITALITY: string = ${JSON.stringify(hospitality.glossary)};

export const GLOSSARY_FNB_LEASING_KO_JA: string = ${JSON.stringify(fnb.glossary)};

export const DOMAIN_HOSPITALITY = ${JSON.stringify(hospitality.domain)};

export const DOMAIN_FNB_LEASING = ${JSON.stringify(fnb.domain)};

export interface GlossaryPreset {
  id: string;
  label: string;
  languagePair: LanguagePairId;
  glossary: string;
  domain: string;
}

export const PRESETS: GlossaryPreset[] = [
${entries.join("\n")}
];

export function findPreset(id: string): GlossaryPreset | undefined {
  return PRESETS.find((preset) => preset.id === id);
}
`;

fs.writeFileSync(OUT, ts);
console.log(`wrote ${OUT} (${ts.length} chars, ${MAP.length} presets)`);
